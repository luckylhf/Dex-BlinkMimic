"""Frozen full-library references with persistent global frame IDs.

Stores the float32 generalized reference states, computes exactly the existing FK
at queried frames, and keeps the upstream time-bin prior. No rotations, replay
invalidation, corpus reweighting, reference quantization or data growth.
"""
import json
from pathlib import Path
import torch
from blinkmimic.motion import MotionLib
from dex_mimic.common import sha

STATE_FIELDS = ('root_p','root_R','root_v','root_w','q','qd')
AUX_FIELDS = ('root_v_local','root_w_local','clip_id','frame_bin','clip_len','clip_start','clip_end','bin_clip','bin_start','bin_prior','ref_contact')


class CompactMotionLib(MotionLib):
    def __init__(self, path, kin, device):
        path = Path(path)
        report = json.loads((path.parent/'compact_receipt.json').read_text())
        assert report['complete'] and sha(path.parent/'manifest.json') == report['manifest_sha256']
        assert sha(path) == report['pack_sha256']
        pack = torch.load(path,map_location='cpu',weights_only=True,mmap=True)
        self.device, self.kin = device, kin
        self.feet = report["feet_indices"]
        self.names = pack['names']
        self.num_frames, self.num_bins = pack['num_frames'], pack['num_bins']
        for key, value in pack['tensors'].items():
            setattr(self,key,value.to(device))
        self.root_gz = self.root_R[:,2,2]
        self.manifest_sha256 = report['manifest_sha256']

    def body_state(self, f):
        return self.kin.forward(*self.ref_state(f))

    def set_ref_contact(self, feet, margin=.015, vmax=.5, q=.05):
        # Generated by the upstream rule at cache-build time on the same model.
        assert feet == self.feet
        assert (margin,vmax,q) == (.015,.5,.05)


def build_compact(dataset, robot, kin):
    """Build bounded temporary FK batches, with one immutable global frame space."""
    dataset = Path(dataset)
    manifest = json.loads((dataset/'manifest.json').read_text())
    assert manifest['complete']
    rows = manifest['motions']
    total, clips = manifest['frames'], len(rows)
    lengths = torch.tensor([r['frames'] for r in rows],dtype=torch.long)
    starts = torch.cat((torch.zeros(1,dtype=torch.long),lengths[:-1].cumsum(0)))
    ends = starts+lengths-1
    counts = (lengths-2)//50+1
    bin_clip = torch.repeat_interleave(torch.arange(clips),counts)
    bin_first = torch.cat((torch.zeros(1,dtype=torch.long),counts[:-1].cumsum(0)))
    bin_start = starts[bin_clip]+(torch.arange(len(bin_clip))-bin_first[bin_clip])*50
    tensors = dict(clip_len=lengths,clip_start=starts,clip_end=ends,
                   clip_id=torch.empty(total,dtype=torch.long),frame_bin=torch.empty(total,dtype=torch.long),
                   bin_clip=bin_clip,bin_start=bin_start,bin_prior=torch.full((len(bin_clip),),1/len(bin_clip)),
                   ref_contact=torch.empty(total,2))
    feet = [robot.tracked_bodies.index(b) for b in robot.feet]
    for first in range(0,clips,256):
        part = rows[first:first+256]
        files = [str(dataset/'motions'/r['training_file']) for r in part]
        for r,f in zip(part,files): assert sha(f)==r['training_sha256']
        lib = MotionLib(files,kin,kin.device,robot.load_motion)
        begin = int(starts[first]); finish=begin+lib.num_frames
        for key in STATE_FIELDS+('root_v_local','root_w_local'):
            value = getattr(lib,key).cpu()
            if key not in tensors: tensors[key]=torch.empty((total,)+value.shape[1:],dtype=value.dtype)
            tensors[key][begin:finish].copy_(value)
        z = lib.body_p[:,feet,2]; vh = lib.body_v[:,feet,:2].norm(dim=-1)
        for j,row in enumerate(part):
            c=first+j; s,e=int(starts[c]),int(ends[c])+1
            ls,le=s-begin,e-begin
            floor=z[ls:le].quantile(.05,dim=0)
            tensors['ref_contact'][s:e]=((z[ls:le]<floor+.015)&(vh[ls:le]<.5)).float().cpu()
            tensors['clip_id'][s:e]=c
            local=torch.arange(e-s)//50
            tensors['frame_bin'][s:e]=bin_first[c]+local.clamp(max=int(counts[c])-1)
        print('COMPACT_BUILD',first+len(part),'/',clips,'frames',finish,'/',total,flush=True)
        del lib
    pack=dict(format='dex-compact-full-reference-v1',names=[r['name'] for r in rows],
              num_frames=total,num_bins=len(bin_clip),tensors=tensors)
    target=dataset/'compact.pt'; torch.save(pack,target)
    from dex_mimic.common import atomic
    atomic(dataset/'compact_receipt.json',dict(complete=True,format=pack['format'],
           manifest_sha256=sha(dataset/'manifest.json'),pack_sha256=sha(target),
           tensor_bytes=sum(t.numel()*t.element_size() for t in tensors.values()),feet_indices=feet,
           clips=clips,frames=total,bins=len(bin_clip),dtype='float32',
           feature_rule='upstream MotionLib; reference FK evaluated on demand',
           prior='uniform time bins, no corpus weights',source_arrays_unchanged=True))
    print('COMPACT_READY',target,flush=True)
